      applyCoupon() {
        let app = this;
        if(app.form.plan_year == '')
        {
          alert("Please select Package.");
          return false;
        }

        if( app.form.coupon_code == '' ) {
          alert("Coupon code is required!!");
          return false;
        }

        axios.get( app.url + '/admin/coupon/apply/' + app.form.coupon_code ).then( (response) => {
          if (response.data.success) {
            app.coupon_msg = true;
              if (response.data.data.type == 'fixedamount') 
              {
                let additional_report = this.form.additional_report;
                let price = this.form.plen_select_price;
                let t_price = 0;
                if(additional_report != '')
                {
                  t_price += price + (20 * additional_report);
                }
                else
                {
                  t_price += price;
                }
                let coupon_amount = response.data.data.amount;
                if(t_price - coupon_amount != '')
                {
                  app.coupon_amount =  '-$'+coupon_amount.toFixed(2);
                  //app.Subtotal = price;
                  //app.coupon_price = price - coupon_amount;
                  app.Subtotal = t_price.toFixed(2);
                  app.coupon_price = (t_price - coupon_amount).toFixed(2);
                  app.coupon_name  = app.form.coupon_code;
                  app.coupon_msg = true;
                }
              }
              else if (response.data.data.type == 'percentage') {
                let additional_report = this.form.additional_report;
                let price = this.form.plen_select_price;
                let t_price = 0;
                if(additional_report != '')
                {
                  t_price += price + (20 * additional_report);
                }
                else
                {
                  t_price += price;
                }
                let coupon_amount = response.data.data.amount;
                let after_discount = t_price - (t_price * coupon_amount / 100);
                if(after_discount != '')
                {
                  app.coupon_amount =  coupon_amount+'%';
                  app.Subtotal = t_price.toFixed(2);
                  app.coupon_price = after_discount.toFixed(2);
                  app.coupon_name  = app.form.coupon_code;
                  app.coupon_msg = true;
                }
              }
            jQuery("#coupon_code").attr("disabled", true);
            showSuccessMessage(response.data.data.msg);
          } 
          else 
          {
            showErrorMessage(response.data.data.msg);
          }
        }).catch( (error) => {
          alert('Something went wrong!!');
        });
