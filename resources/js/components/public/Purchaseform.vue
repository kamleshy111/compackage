      purchasePlan(e) {

        let app = this;
        e.preventDefault();

        let password = app.form.password;
        let confirm_password = app.form.confirm_password;

        // If password not entered
        if (password == '' && ! app.user ) {
          app.showErrorMessage1("Please enter Password");
          moveUp();
          return false;
        } else if (confirm_password == '' && ! app.user ) {
          app.showErrorMessage1("Please enter confirm password.");
          moveUp();
          return false;
        } else if (password != confirm_password && ! app.user ) {
          app.showErrorMessage1("Password did not match.");
          moveUp();
          return false;
        }
        
        if( ! app.recaptcha_verified ) {
          app.showErrorMessage1("reCaptcha is required.");
          moveUp();
          return false;
        }
        
        jQuery('input, select').removeClass('border-2 border-rose-600');
        app.viewLoader = true;

        stripe.confirmCardSetup(app.stripeintent, {
            payment_method: {
                card: card,
                billing_details: {
                name: app.form.firstname + ' ' + app.form.lastname,
                email: app.form.email
                },
            },
        })
        .then(function (result) {
            if (result.error) {
                app.viewLoader = false;
                if( result.error.code == "setup_intent_unexpected_state" ) {
                  card.clear();
                  //alert('To keep your card safe, please reload the page and start over.');
                  //location.reload();
                } else {
                  app.showErrorMessage1(result.error.message);
                }
            } else {
                // Call charge payment now.
                app.form.token_data = result.setupIntent.id;
                app.form.payment_method = result.setupIntent.payment_method;

                axios.post(app.url + '/plan-purchase', app.form).then((response) => {
                    if (response.data.success) {
                        app.form.sales_id = response.data.data.sales_id;

                        axios.post( app.url + '/purchase/charge', app.form).then((resp) => {
                            if (resp.data.success) {
                                showSuccessMessage(resp.data.data.msg);
                                app.viewLoader = false;
                                setTimeout(() => {
                                location.href = app.url + '/webapp/dashboard';
                                }, 3000);
                            } else {
                                app.viewLoader = false;
                                app.showErrorMessage1(resp.data.data.msg);
                            }
                        })
                        .catch(function (resp) {
                            app.viewLoader = false;
                            app.showErrorMessage1("Something went wrong please try again.");
                        });
                    } else {
                        app.viewLoader = false;
                        app.showFormError(response.data.data.key, response.data.data.msg)
                    }
                }).catch((error) => {
                    app.showErrorMessage1(error);
                    app.viewLoader = false;
                });
            }
        });
